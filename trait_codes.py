_TABLES = {"normal": NORMAL, "new": NEW, "train": TRAINING, "coach": TRAINING}


def name_of(kind: str, code) -> str | None:
    """코드 → 이름. 잠김(-2)·빈칸(-1)·숫자 아님은 None(집계에서 뺀다) · 모르는 코드는 "코드 N"(예외 없음).
    kind 는 `KINDS`. 모르는 kind 는 모르는 코드와 같이 "코드 N"."""
    if isinstance(code, bool) or not isinstance(code, int):
        return None
    if code in (LOCKED, EMPTY) or code < 0:
        return None
    return _TABLES.get(kind, {}).get(code) or f"코드 {code}"


def order_slots(traits: tuple[int, int, int]) -> tuple[int, int, int]:
    """(칸0, 칸1, 훈련) → (일반, 신규, 훈련). 번들 `yv` 와 같은 규칙: 거꾸로라는 증거(칸0 이 신규 표 · 칸1 이 일반 표)가 있고
    제 순서라는 증거(칸0 이 일반 표 · 칸1 이 신규 표)가 없으면 바꾼다 — 한쪽이 빈칸(-1)이어도 다른 쪽 코드로 가린다."""
    a, b, c = traits
    reverse = a in NEW or b in NORMAL
    normal = a in NORMAL or b in NEW
    if (a in NEW and b in NORMAL) or (reverse and not normal):
        return (b, a, c)
    return traits


def is_open_slot(code) -> bool:
    """값이 들어 있는 칸인가 — 잠김·빈칸·숫자 아님이 아니면."""
    return isinstance(code, int) and not isinstance(code, bool) and code >= 0
